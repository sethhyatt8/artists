export type CategoryOptions = {
  category: string
  prompts: string[]
}

function shuffle<T>(items: T[]) {
  const next = [...items]
  for (let i = next.length - 1; i > 0; i -= 1) {
    const j = Math.floor(Math.random() * (i + 1))
    const a = next[i]
    const b = next[j]
    if (a === undefined || b === undefined) continue
    next[i] = b
    next[j] = a
  }
  return next
}

export const CATEGORIES_PER_DEAL = 5
export const PROMPTS_PER_CATEGORY = 5

export function dealPromptOptions(used: string[] = []): CategoryOptions[] {
  const usedSet = new Set(used.map(normalizeAnswer))
  const groups: CategoryOptions[] = []
  for (const category of shuffle(Object.keys(CATEGORIES))) {
    const unused = shuffle(CATEGORIES[category] ?? []).filter(
      (prompt) => !usedSet.has(normalizeAnswer(prompt)),
    )
    if (unused.length === 0) continue
    const prompts = unused.slice(0, PROMPTS_PER_CATEGORY)
    for (const prompt of prompts) usedSet.add(normalizeAnswer(prompt))
    groups.push({ category, prompts })
    if (groups.length === CATEGORIES_PER_DEAL) break
  }
  if (groups.length > 0) return groups
  return dealFresh()
}

function dealFresh(): CategoryOptions[] {
  const usedSet = new Set<string>()
  const names = shuffle(Object.keys(CATEGORIES)).slice(0, CATEGORIES_PER_DEAL)
  return names.map((category) => {
    const prompts = shuffle(CATEGORIES[category] ?? [])
      .filter((prompt) => !usedSet.has(normalizeAnswer(prompt)))
      .slice(0, PROMPTS_PER_CATEGORY)
    for (const prompt of prompts) usedSet.add(normalizeAnswer(prompt))
    return { category, prompts }
  })
}

export function normalizeAnswer(value: string) {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9 ]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
}

export function mergeUsedPrompts(existing: string[], extra: string[]) {
  const seen = new Set(existing.map(normalizeAnswer))
  const next = [...existing]
  for (const prompt of extra) {
    const key = normalizeAnswer(prompt)
    if (!key || seen.has(key)) continue
    seen.add(key)
    next.push(prompt)
  }
  return next
}

export function promptsFromOptions(options: CategoryOptions[]) {
  return options.flatMap((group) => group.prompts)
}

function stem(word: string) {
  if (word.length >= 6 && word.endsWith('ing')) {
    return word.slice(0, -3)
  }
  if (word.length >= 5 && word.endsWith('ed')) {
    return word.slice(0, -2)
  }
  if (word.length > 3 && word.endsWith('s') && !word.endsWith('ss')) {
    return word.slice(0, -1)
  }
  return word
}

export function contentWords(value: string) {
  return normalizeAnswer(value)
    .split(' ')
    .filter((word) => word.length >= 2 && !STOPWORDS.has(word))
    .map(stem)
}

export function answersMatch(guess: string, prompt: string) {
  const guessNorm = normalizeAnswer(guess)
  const promptNorm = normalizeAnswer(prompt)
  if (!guessNorm || !promptNorm) return false
  if (guessNorm === promptNorm) return true

  const guessWords = contentWords(guess)
  const promptWords = contentWords(prompt)
  if (guessWords.length === 0 || promptWords.length === 0) return false

  const guessSet = new Set(guessWords)
  if (promptWords.every((word) => guessSet.has(word))) return true

  if (promptWords.length >= 4) {
    const longest = [...promptWords].sort((a, b) => b.length - a.length)[0]
    const hits = promptWords.filter((word) => guessSet.has(word))
    return Boolean(longest && guessSet.has(longest) && hits.length >= promptWords.length - 1)
  }
  return false
}

export function maskSecret(value: string) {
  return value.replace(/[A-Za-z0-9]/g, '*')
}

export function optionExists(options: CategoryOptions[], category: string, prompt: string) {
  const group = options.find((item) => item.category === category)
  return Boolean(group?.prompts.includes(prompt))
}
